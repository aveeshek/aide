def _collect_imports(tree: ast.Module) -> dict[str, ImportedSymbol]:
    """Build the local-name -> imported-symbol table used for every resolution."""
    imports: dict[str, ImportedSymbol] = {}
    for node in ast.walk(tree):
        if isinstance(node, ast.Import):
            for alias in node.names:
                if alias.asname:
                    local, module = alias.asname, alias.name
                else:
                    # ``import a.b`` binds ``a``, not ``a.b``.
                    local = module = alias.name.split(".", 1)[0]
                imports.setdefault(
                    local, ImportedSymbol(module=module, name=None, lineno=node.lineno)
                )
        elif isinstance(node, ast.ImportFrom):
            for alias in node.names:
                if alias.name == "*":
                    # A star import binds unknown names; nothing can be resolved from it.
                    continue
                local = alias.asname or alias.name
                imports.setdefault(
                    local,
                    ImportedSymbol(
                        module=node.module or "",
                        name=alias.name,
                        lineno=node.lineno,
                        level=node.level,
                    ),
                )
    return imports


def _is_framework_module(module: str, roots: tuple[str, ...]) -> bool:
    return any(module == root or module.startswith(f"{root}.") for root in roots)


def _resolve_framework_symbol(
    imports: dict[str, ImportedSymbol], node: ast.expr, roots: tuple[str, ...]
) -> str | None:
    """Return the framework symbol name ``node`` refers to, following import aliases.

    Handles ``from fastapi import APIRouter``, ``from fastapi import APIRouter as R``,
    ``import fastapi`` + ``fastapi.APIRouter``, and ``fastapi.routing.APIRouter``.
    """
    dotted = _dotted_expression(node)
    if dotted is None:
        return None
    parts = dotted.split(".")
    symbol = parts[-1]
    imported = imports.get(parts[0])
    if imported is None:
        return None
    if len(parts) == 1:
        if imported.name is None or imported.level:
            return None
        if not _is_framework_module(imported.module, roots):
            return None
        # Return the imported symbol, not the local alias, so ``BaseModel as PydanticBase``
        # and ``APIRouter as Router`` are recognized.
        return imported.name
    base = imported.module if imported.name is None else f"{imported.module}.{imported.name}"
    owner = ".".join([base, *parts[1:-1]])
    return symbol if _is_framework_module(owner, roots) else None


def _surface_constructor(imports: dict[str, ImportedSymbol], node: ast.expr) -> str | None:
    """Return ``FastAPI`` or ``APIRouter`` when ``node`` is that constructor."""
    symbol = _resolve_framework_symbol(imports, node, (_FASTAPI_ROOT_MODULE,))
    return symbol if symbol in _SURFACE_CONSTRUCTORS else None


def _parameter_marker(imports: dict[str, ImportedSymbol], node: ast.expr | None) -> str | None:
    """Return the FastAPI parameter marker used anywhere inside ``node``.

    A marker in a default (``= Depends(...)``) or inside ``Annotated[...]`` metadata proves
    how FastAPI sources the parameter, which is what decides body-versus-not.
    """
    if node is None:
        return None
    for candidate in ast.walk(node):
        if not isinstance(candidate, ast.Call):
            continue
        symbol = _resolve_framework_symbol(imports, candidate.func, _FRAMEWORK_MODULE_ROOTS)
        if symbol in FASTAPI_BODY_MARKERS or symbol in FASTAPI_NON_BODY_MARKERS:
            return symbol
    return None


def _static_prefix(
    source: str, call: ast.Call | None, keyword_name: str = "prefix"
) -> tuple[str, bool, str | None]:
    """Read a ``prefix=`` keyword.

    Returns ``(prefix, resolved, unresolved_expression)``. An absent keyword is resolved and
    contributes nothing. A non-constant keyword contributes nothing and is reported.
    """
    if call is None:
        return "", True, None
    node = _keyword_node(call, keyword_name)
    if node is None:
        return "", True, None
    literal = _constant_string(node)
    if literal is not None:
        return literal, True, None
    return "", False, _expression_text(source, node)


def _surface_definition(
    source: str, constructor: str, variable: str, call: ast.Call, node: ast.AST
) -> SurfaceDefinition:
    prefix, prefix_resolved, prefix_expression = _static_prefix(source, call)
    root_path_node = _keyword_node(call, "root_path")
    return SurfaceDefinition(
        constructor=constructor,
        variable=variable,
        prefix=prefix,
        prefix_resolved=prefix_resolved,
        prefix_expression=prefix_expression,
        tags=_constant_strings(_keyword_node(call, "tags")),
        title=_constant_string(_keyword_node(call, "title")),
        root_path_expression=_expression_text(source, root_path_node),
        lineno=getattr(node, "lineno", call.lineno),
        end_lineno=getattr(node, "end_lineno", None) or call.lineno,
    )


def _field_default(
    source: str, name: str, value: ast.expr | None
) -> tuple[Any | None, str | None, bool, str | None]:
    """Project a field default safely.

    Returns ``(default, default_expression, redacted, withheld_text)``. Literals are copied
    as-is; anything else is recorded as source text only. Nothing is ever evaluated, and a
    credential-shaped field name or expression yields a placeholder instead of a value.
    """
    if value is None:
        return None, None, False, None
    secret = is_secret_name(name)
    if isinstance(value, ast.Constant) and isinstance(value.value, str | int | float | bool | None):
        literal = value.value
        if secret:
            return REDACTED_PLACEHOLDER, None, True, str(literal)
        return literal, None, False, None
    expression = _expression_text(source, value)
    if expression is None:
        return None, None, False, None
    if secret or contains_secret_marker(expression):
        return None, REDACTED_PLACEHOLDER, True, expression
    return None, expression, False, None


def _class_declaration(
    source: str, node: ast.ClassDef, withheld: set[str]
) -> ClassDeclaration:
    """Collect a class definition and its annotated fields."""
    fields: list[FieldDeclaration] = []
    for statement in node.body:
        if not isinstance(statement, ast.AnnAssign) or not isinstance(statement.target, ast.Name):
            continue
        name = statement.target.id
        default, default_expression, redacted, withheld_text = _field_default(
            source, name, statement.value
        )
        if withheld_text:
            withheld.add(withheld_text)
        fields.append(
            FieldDeclaration(
                name=name,
                annotation=_expression_text(source, statement.annotation),
                default=default,
                default_expression=default_expression,
                redacted=redacted,
                lineno=statement.lineno,
            )
        )
    base_expressions = tuple(
        _expression_text(source, base) or "<unresolved>" for base in node.bases
    )
    return ClassDeclaration(
        name=node.name,
        bases=base_expressions,
        base_nodes=tuple(node.bases),
        fields=tuple(fields),
        lineno=node.lineno,
        end_lineno=node.end_lineno or node.lineno,
    )


def _handler_parameters(
    source: str, imports: dict[str, ImportedSymbol], node: ast.FunctionDef | ast.AsyncFunctionDef
) -> tuple[ParameterDeclaration, ...]:
    """Collect handler parameters with annotations and any FastAPI marker."""
    arguments = node.args
    positional = list(arguments.posonlyargs) + list(arguments.args)
    # ``defaults`` aligns with the tail of the positional parameters.
    padding = len(positional) - len(arguments.defaults)
    paired: list[tuple[ast.arg, ast.expr | None]] = []
    for index, argument in enumerate(positional):
        default = arguments.defaults[index - padding] if index >= padding else None
        paired.append((argument, default))
    for index, argument in enumerate(arguments.kwonlyargs):
        default = arguments.kw_defaults[index] if index < len(arguments.kw_defaults) else None
        paired.append((argument, default))

    parameters: list[ParameterDeclaration] = []
    for argument, default in paired:
        if argument.arg in ("self", "cls"):
            continue
        marker = _parameter_marker(imports, default) or _parameter_marker(
            imports, argument.annotation
        )
        parameters.append(
            ParameterDeclaration(
                name=argument.arg,
                annotation=argument.annotation,
                annotation_expression=_expression_text(source, argument.annotation),
                marker=marker,
                lineno=argument.lineno,
            )
        )
    return tuple(parameters)


def _route_declaration(
    source: str,
    imports: dict[str, ImportedSymbol],
    node: ast.FunctionDef | ast.AsyncFunctionDef,
    decorator: ast.Call,
    owner: str,
    method: str,
) -> RouteDeclaration:
    """Read one route decorator plus its handler signature."""
    path_node = decorator.args[0] if decorator.args else _keyword_node(decorator, "path")
    literal_path = _constant_string(path_node)
    status_node = _keyword_node(decorator, "status_code")
    status_code = (
        status_node.value
        if isinstance(status_node, ast.Constant) and isinstance(status_node.value, int)
        else None
    )
    deprecated_node = _keyword_node(decorator, "deprecated")
    deprecated = (
        deprecated_node.value
        if isinstance(deprecated_node, ast.Constant) and isinstance(deprecated_node.value, bool)
        else None
    )
    response_model = _keyword_node(decorator, "response_model")
    return RouteDeclaration(
        owner_variable=owner,
        method=method,
        path=literal_path or "",
        path_resolved=literal_path is not None,
        path_expression=None if literal_path is not None else _expression_text(source, path_node),
        function_name=node.name,
        decorator_source=_expression_text(source, decorator) or "",
        decorator_lineno=decorator.lineno,
        function_lineno=node.lineno,
        function_end_lineno=node.end_lineno or node.lineno,
        response_model=response_model,
        response_model_expression=_expression_text(source, response_model),
        status_code=status_code,
        status_code_expression=None if status_code is not None else _expression_text(
            source, status_node
        ),
        tags=_constant_strings(_keyword_node(decorator, "tags")),
        deprecated=deprecated,
        operation_id=_constant_string(_keyword_node(decorator, "operation_id")),
        parameters=_handler_parameters(source, imports, node),
    )


def analyze_module(
    source: str,
    tree: ast.Module,
    *,
    relative_path: str,
    service: str,
    service_root: str,
    module: str,
    is_package: bool,
    warnings: list[str],
) -> ModuleFacts:
    """Gather every FastAPI-relevant fact from one parsed module.

    A single :func:`ast.walk` collects imports, surface constructors, ``include_router``
    calls, route decorators, and class definitions. Nothing is imported or evaluated.
    """
    imports = _collect_imports(tree)
    surfaces: dict[str, SurfaceDefinition] = {}
    classes: dict[str, ClassDeclaration] = {}
    functions: set[str] = set()
    includes: list[IncludeCall] = []
    routes: list[RouteDeclaration] = []
    withheld: set[str] = set()
    # Candidate factories: function name -> returned local variable name. Confirmed only
    # after the walk, once every router assignment in the module is known.
    returned_names: dict[str, str] = {}

    for node in ast.walk(tree):
        # --- surface assignments: ``app = FastAPI(...)`` / ``router = APIRouter(...)`` ---
        targets: list[ast.Name] = []
        value: ast.expr | None = None
        if isinstance(node, ast.Assign):
            targets = [item for item in node.targets if isinstance(item, ast.Name)]
            value = node.value
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            targets = [node.target]
            value = node.value
        if targets and isinstance(value, ast.Call):
            constructor = _surface_constructor(imports, value.func)
            if constructor is not None:
                for target in targets:
                    if target.id in surfaces:
                        warnings.append(
                            f"{relative_path}: {target.id!r} is assigned a "
                            f"{constructor} more than once; kept the first definition "
                            f"at line {surfaces[target.id].lineno}"
                        )
                        continue
                    surfaces[target.id] = _surface_definition(
                        source, constructor, target.id, value, node
                    )

        # --- include_router calls ---
        if (
            isinstance(node, ast.Call)
            and isinstance(node.func, ast.Attribute)
            and node.func.attr == "include_router"
            and isinstance(node.func.value, ast.Name)
        ):
            argument = node.args[0] if node.args else _keyword_node(node, "router")
            if argument is None:
                warnings.append(
                    f"{relative_path}:{node.lineno}: include_router call has no router "
                    f"argument; skipped"
                )
            else:
                prefix, prefix_resolved, prefix_expression = _static_prefix(source, node)
                includes.append(
                    IncludeCall(
                        parent_variable=node.func.value.id,
                        argument=argument,
                        argument_expression=_expression_text(source, argument) or "",
                        prefix=prefix,
                        prefix_resolved=prefix_resolved,
                        prefix_expression=prefix_expression,
                        lineno=node.lineno,
                    )
                )

        # --- functions: handlers, route decorators, and router factories ---
        if isinstance(node, ast.FunctionDef | ast.AsyncFunctionDef):
            functions.add(node.name)
            for statement in ast.walk(node):
                if isinstance(statement, ast.Return) and isinstance(statement.value, ast.Name):
                    returned_names.setdefault(node.name, statement.value.id)
            for decorator in node.decorator_list:
                if not isinstance(decorator, ast.Call):
                    # ``@router.get`` without a call is not a valid FastAPI route.
                    continue
                if not isinstance(decorator.func, ast.Attribute):
                    continue
                if not isinstance(decorator.func.value, ast.Name):
                    continue
                method = decorator.func.attr.lower()
                if method not in HTTP_METHODS:
                    continue
                routes.append(
                    _route_declaration(
                        source,
                        imports,
                        node,
                        decorator,
                        decorator.func.value.id,
                        method,
                    )
                )

        # --- class definitions (schema candidates) ---
        if isinstance(node, ast.ClassDef):
            if node.name in classes:
                warnings.append(
                    f"{relative_path}: class {node.name!r} is defined more than once; "
                    f"kept the first definition at line {classes[node.name].lineno}"
                )
            else:
                classes[node.name] = _class_declaration(source, node, withheld)

    factories = {
        function: variable
        for function, variable in sorted(returned_names.items())
        if variable in surfaces and not surfaces[variable].is_app
    }

    return ModuleFacts(
        relative_path=relative_path,
        service=service,
        service_root=service_root,
        module=module,
        is_package=is_package,
        imports=imports,
        surfaces=surfaces,
        factories=factories,
        includes=tuple(sorted(includes, key=lambda item: (item.lineno, item.parent_variable))),
        routes=tuple(
            sorted(routes, key=lambda item: (item.decorator_lineno, item.method, item.path))
        ),
        classes=classes,
        functions=frozenset(functions),
        withheld_values=frozenset(withheld),
    )



def _resolve_include_target(
    index: SourceIndex, facts: ModuleFacts, include: IncludeCall
) -> NodeKey | None:
    """Resolve the router argument of an ``include_router`` call to a surface node."""
    argument = include.argument
    if isinstance(argument, ast.Call):
        # ``app.include_router(init_router())``: only a zero-argument factory whose body
        # returns a router defined in the same module is statically traceable.
        if argument.args or argument.keywords:
            return None
        resolution = index.resolve_expression(facts.service, facts.module, argument.func)
        if (
            resolution.kind != RESOLUTION_FACTORY
            or resolution.module is None
            or resolution.name is None
        ):
            return None
        target = index.facts(facts.service, resolution.module)
        if target is None:
            return None
        variable = target.factories.get(resolution.name)
        return None if variable is None else NodeKey(facts.service, resolution.module, variable)

    resolution = index.resolve_expression(facts.service, facts.module, argument)
    if (
        resolution.kind in (RESOLUTION_ROUTER, RESOLUTION_APP)
        and resolution.module is not None
        and resolution.name is not None
    ):
        return NodeKey(facts.service, resolution.module, resolution.name)
    return None


def _build_router_graph(
    index: SourceIndex,
    modules: list[ModuleFacts],
    repository: str,
    commit: str,
    unresolved_routes: list[UnresolvedRoute],
) -> RouterGraph:
    """Build the app/router mount graph from ``include_router`` evidence only."""
    surfaces: dict[NodeKey, SurfaceDefinition] = {}
    for facts in modules:
        for variable in sorted(facts.surfaces):
            surfaces[NodeKey(facts.service, facts.module, variable)] = facts.surfaces[variable]

    incoming: dict[NodeKey, list[MountEdge]] = {}
    for facts in modules:
        for include in facts.includes:
            provenance = Provenance(
                repository=repository,
                commit=commit,
                source_path=facts.relative_path,
                symbol=facts.qualified(include.parent_variable),
                line_start=include.lineno,
                line_end=include.lineno,
            )
            parent = NodeKey(facts.service, facts.module, include.parent_variable)
            if parent not in surfaces:
                unresolved_routes.append(
                    UnresolvedRoute(
                        reason_code="unresolved_include_parent",
                        detail=(
                            f"include_router was called on {include.parent_variable!r}, which "
                            f"is not a FastAPI or APIRouter defined in this module"
                        ),
                        expression=include.argument_expression,
                        provenance=provenance,
                        service=facts.service,
                    )
                )
                continue
            child = _resolve_include_target(index, facts, include)
            if child is None or child not in surfaces:
                unresolved_routes.append(
                    UnresolvedRoute(
                        reason_code="unresolved_include_target",
                        detail=(
                            "the included router could not be traced to an APIRouter "
                            "definition in scanned source; no mount edge was created"
                        ),
                        expression=include.argument_expression,
                        provenance=provenance,
                        service=facts.service,
                    )
                )
                continue
            if not include.prefix_resolved:
                unresolved_routes.append(
                    UnresolvedRoute(
                        reason_code="dynamic_include_prefix",
                        detail=(
                            f"include_router mounts {child.describe()} with a prefix that is "
                            f"not a string literal; the prefix contributes nothing to the "
                            f"effective path and affected endpoints are marked partial"
                        ),
                        expression=include.prefix_expression,
                        provenance=provenance,
                        service=facts.service,
                    )
                )
            incoming.setdefault(child, []).append(
                MountEdge(
                    parent=parent,
                    child=child,
                    prefix=include.prefix,
                    prefix_resolved=include.prefix_resolved,
                    prefix_expression=include.prefix_expression,
                    relative_path=facts.relative_path,
                    lineno=include.lineno,
                )
            )

    for node in sorted(surfaces, key=lambda item: (item.service, item.module, item.variable)):
        surface = surfaces[node]
        if surface.prefix_resolved:
            continue
        facts = index.facts(node.service, node.module)
        unresolved_routes.append(
            UnresolvedRoute(
                reason_code="dynamic_router_prefix",
                detail=(
                    f"{surface.constructor}(prefix=...) for {node.describe()} is not a string "
                    f"literal; the prefix contributes nothing to the effective path"
                ),
                expression=surface.prefix_expression,
                provenance=Provenance(
                    repository=repository,
                    commit=commit,
                    source_path=facts.relative_path if facts else node.module,
                    symbol=f"{node.module}.{node.variable}" if node.module else node.variable,
                    line_start=surface.lineno,
                    line_end=surface.end_lineno,
                ),
                service=node.service,
            )
        )

    ordered = {
        node: tuple(
            sorted(edges, key=lambda item: (item.relative_path, item.lineno, item.parent.variable))
        )
        for node, edges in incoming.items()
    }
    return RouterGraph(surfaces=surfaces, incoming=ordered)


def _base_resolution_label(
    index: SourceIndex, service: str, module: str, declaration: ClassDeclaration, confirmed: bool
) -> str:
    """Describe how far a class's base chain could be traced. Never a guess."""
    if confirmed:
        return "pydantic_basemodel"
    if not declaration.base_nodes:
        return "no_declared_base"
    kinds = {
        index.resolve_expression(service, module, base).kind for base in declaration.base_nodes
    }
    if RESOLUTION_EXTERNAL in kinds:
        return "external_base"
    if RESOLUTION_CLASS in kinds:
        return "local_non_model_base"
    return "unresolved_base"


def _schema_candidate(
    index: SourceIndex,
    repository: str,
    repository_slug: str,
    commit: str,
    service: str,
    module: str,
    class_name: str,
) -> SchemaCandidate | None:
    """Build a Schema candidate from a class definition found in scanned source."""
    facts = index.facts(service, module)
    if facts is None:
        return None
    declaration = facts.classes.get(class_name)
    if declaration is None:
        return None
    qualified_name = f"{module}.{class_name}" if module else class_name
    confirmed = index.is_pydantic_model(service, module, class_name)
    return SchemaCandidate(
        id=schema_id(repository_slug, service, qualified_name),
        kind=SCHEMA_KIND,
        title=class_name,
        service=service,
        qualified_name=qualified_name,
        pydantic_confirmed=confirmed,
        base_resolution=_base_resolution_label(
            index, service, module, declaration, confirmed
        ),
        bases=declaration.bases,
        fields=declaration.fields,
        provenance=Provenance(
            repository=repository,
            commit=commit,
            source_path=facts.relative_path,
            symbol=qualified_name,
            line_start=declaration.lineno,
            line_end=declaration.end_lineno,
        ),
    )


def _body_parameters(
    route: RouteDeclaration, path_parameters: frozenset[str]
) -> tuple[ParameterDeclaration, ...]:
    """Select parameters that FastAPI would treat as a request body.

    A parameter carrying a ``Depends``/``Query``/``Path``/``Header``/``Cookie``/``Form``/
    ``File`` marker is sourced from somewhere other than the body. A parameter named in the
    path template is a path parameter unless it is explicitly marked ``Body``.
    """
    selected: list[ParameterDeclaration] = []
    for parameter in route.parameters:
        if parameter.annotation is None:
            continue
        explicit_body = parameter.marker in FASTAPI_BODY_MARKERS
        if parameter.marker in FASTAPI_NON_BODY_MARKERS and not explicit_body:
            continue
        if parameter.name in path_parameters and not explicit_body:
            continue
        selected.append(parameter)
    return tuple(selected)


def path_parameter_names(effective_path: str) -> frozenset[str]:
    """Names declared as ``{param}`` in a route path template."""
    names = {
        match.split(":", 1)[0].strip()
        for match in re.findall(r"\{([^{}]*)\}", effective_path)
    }
    return frozenset(name for name in names if name)


def extract_fastapi(
    record: RepositoryRecord,
    commit: str,
    *,
    source_kind: str = SOURCE_KIND,
) -> FastApiExtraction:
    """Extract FastAPI APIs, endpoints, and schemas from Python source with AST only.

    ``commit`` must already be verified against the manifest baseline by the caller. The
    inspected repository is only ever read; no module is imported and no service is started.
    """
    del source_kind  # Source selection is fixed to the manifest 'code' kind for this pass.
    repository = record.id
    repository_slug = normalize_token(record.id)
    warnings: list[str] = []
    unresolved_routes: list[UnresolvedRoute] = []
    unresolved_schemas: list[UnresolvedSchema] = []
    unresolved_schema_keys: set[tuple[str, ...]] = set()

    candidates, skipped = _discover_source_files(record)
    modules: list[ModuleFacts] = []
    scanned: list[str] = []
    withheld: set[str] = set()
    files_per_service: dict[str, int] = {}

    for relative_path in candidates:
        location = service_location(relative_path)
        if location is None:
            skipped.append(
                f"{relative_path}: outside the known application service layout "
                f"({BACKEND_SEGMENT}/{GATEWAY_SEGMENT} or "
                f"{BACKEND_SEGMENT}/{MICROSERVICES_SEGMENT}/<name>)"
            )
            continue
        service, service_root = location
        try:
            text = (record.path / relative_path).read_text(encoding="utf-8")
        except (OSError, UnicodeDecodeError) as exc:
            warnings.append(f"{relative_path}: unreadable, skipped ({exc})")
            continue
        if is_generated_source(text):
            skipped.append(f"{relative_path}: generated source header")
            continue
        try:
            tree = ast.parse(text, filename=relative_path)
        except SyntaxError as exc:
            warnings.append(f"{relative_path}: invalid Python syntax, skipped ({exc.msg})")
            continue

        scanned.append(relative_path)
        files_per_service[service] = files_per_service.get(service, 0) + 1
        facts = analyze_module(
            text,
            tree,
            relative_path=relative_path,
            service=service,
            service_root=service_root,
            module=module_dotted_name(relative_path, service_root),
            is_package=relative_path.rsplit("/", 1)[-1] == "__init__.py",
            warnings=warnings,
        )
        modules.append(facts)
        withheld |= facts.withheld_values

    claimed: dict[tuple[str, str], str] = {}
    for facts in modules:
        key = (facts.service, facts.module)
        previous = claimed.get(key)
        if previous is None:
            claimed[key] = facts.relative_path
        else:
            warnings.append(
                f"{facts.relative_path}: resolves to the same module name "
                f"{facts.module or '<root>'!r} as {previous}; kept {previous} for import "
                f"resolution"
            )

    index = build_source_index(modules)
    graph = _build_router_graph(index, modules, repository, commit, unresolved_routes)

    endpoints: dict[str, EndpointCandidate] = {}
    schemas: dict[str, SchemaCandidate] = {}
    relationships: list[RelationshipCandidate] = []
    schema_links: set[tuple[str, str, str]] = set()

    def link_schema(
        *,
        facts: ModuleFacts,
        node: ast.expr,
        role: str,
        endpoint_identifier: str,
        provenance: Provenance,
        type_expression: str | None,
        parameter: str | None = None,
    ) -> None:
        """Attach one schema reference to an endpoint, or record it as unresolved."""
        if _is_ignorable_annotation(node):
            return
        if (
            _resolve_framework_symbol(facts.imports, node, _FRAMEWORK_MODULE_ROOTS)
            in FRAMEWORK_RUNTIME_TYPES
        ):
            return
        dotted = _dotted_expression(node) or "<unresolved>"
        resolution = index.resolve_expression(facts.service, facts.module, node)
        if (
            resolution.kind == RESOLUTION_CLASS
            and resolution.module is not None
            and resolution.name is not None
        ):
            candidate = _schema_candidate(
                index,
                repository,
                repository_slug,
                commit,
                facts.service,
                resolution.module,
                resolution.name,
            )
            if candidate is not None:
                schemas.setdefault(candidate.id, candidate)
                link = (endpoint_identifier, candidate.id, role)
                if link in schema_links:
                    return
                schema_links.add(link)
                detail: dict[str, Any] = {"symbol": dotted}
                if type_expression:
                    detail["type_expression"] = type_expression
                if parameter:
                    detail["parameter"] = parameter
                relationships.append(
                    RelationshipCandidate(
                        source=endpoint_identifier,
                        type=USES_SCHEMA,
                        target=candidate.id,
                        provenance=provenance,
                        role=role,
                        detail=detail,
                    )
                )
                return

        reason_code = (
            "external_schema_symbol"
            if resolution.kind == RESOLUTION_EXTERNAL
            else "unresolved_schema_symbol"
        )
        reason = resolution.reason or "could not be traced to a class definition"
        key = (reason_code, role, dotted, endpoint_identifier)
        if key in unresolved_schema_keys:
            return
        unresolved_schema_keys.add(key)
        unresolved_schemas.append(
            UnresolvedSchema(
                reason_code=reason_code,
                role=role,
                expression=type_expression or dotted,
                detail=f"{dotted}: {reason}; no Schema entity was created",
                provenance=provenance,
                endpoint=endpoint_identifier,
            )
        )

    for facts in sorted(modules, key=lambda item: item.relative_path):
        for route in facts.routes:
            owner = NodeKey(facts.service, facts.module, route.owner_variable)
            route_provenance = Provenance(
                repository=repository,
                commit=commit,
                source_path=facts.relative_path,
                symbol=facts.qualified(route.function_name),
                line_start=route.decorator_lineno,
                line_end=route.function_end_lineno,
            )
            if owner not in graph.surfaces:
                unresolved_routes.append(
                    UnresolvedRoute(
                        reason_code="unknown_route_owner",
                        detail=(
                            f"decorator @{route.owner_variable}.{route.method} does not target a "
                            f"FastAPI or APIRouter defined in this module; no endpoint created"
                        ),
                        expression=route.decorator_source,
                        provenance=route_provenance,
                        service=facts.service,
                        method=route.method.upper(),
                    )
                )
                continue
            if not route.path_resolved:
                unresolved_routes.append(
                    UnresolvedRoute(
                        reason_code="dynamic_route_path",
                        detail=(
                            "the route path is not a string literal, so the endpoint path "
                            "cannot be known from source; no endpoint created"
                        ),
                        expression=route.path_expression or route.decorator_source,
                        provenance=route_provenance,
                        service=facts.service,
                        method=route.method.upper(),
                    )
                )
                continue

            surface = graph.surfaces[owner]
            for chain in graph.chains(owner):
                effective_path = join_route_path(chain.prefix, route.path)
                identifier = endpoint_id(
                    repository_slug, facts.service, route.method, effective_path
                )
                previous = endpoints.get(identifier)
                if previous is not None:
                    warnings.append(
                        f"Endpoint id {identifier!r} is produced by both "
                        f"{previous.provenance.symbol} ({previous.effective_path}) and "
                        f"{route_provenance.symbol} ({effective_path}); kept the first in "
                        f"deterministic order"
                    )
                    continue

                path_parameters = path_parameter_names(effective_path)
                resolution_label = "complete" if chain.resolved else "partial"
                attributes: dict[str, Any] = {
                    "method": route.method.upper(),
                    "effective_path": effective_path,
                    "decorator_path": route.path,
                    "router_prefix": chain.prefix,
                    "path_resolution": resolution_label,
                    "decorator": route.decorator_source,
                    "handler": facts.qualified(route.function_name),
                    "router": owner.describe(),
                    "mount_path": list(chain.mount_path),
                }
                if path_parameters:
                    attributes["path_parameters"] = sorted(path_parameters)
                tags = sorted(set(surface.tags) | set(route.tags))
                if tags:
                    attributes["tags"] = tags
                if route.status_code is not None:
                    attributes["status_code"] = route.status_code
                elif route.status_code_expression:
                    attributes["status_code_expression"] = route.status_code_expression
                if route.deprecated is not None:
                    attributes["deprecated"] = route.deprecated
                if route.operation_id:
                    attributes["operation_id"] = route.operation_id
                if route.response_model_expression:
                    attributes["response_model"] = route.response_model_expression
                if not chain.resolved:
                    attributes["unresolved_prefix_expressions"] = sorted(
                        set(chain.unresolved_expressions)
                    )

                endpoints[identifier] = EndpointCandidate(
                    id=identifier,
                    kind=ENDPOINT_KIND,
                    title=f"{route.method.upper()} {effective_path}",
                    service=facts.service,
                    api=api_id(repository_slug, facts.service),
                    method=route.method.upper(),
                    effective_path=effective_path,
                    path_resolution=resolution_label,
                    provenance=route_provenance,
                    attributes=attributes,
                )

                decorator_provenance = Provenance(
                    repository=repository,
                    commit=commit,
                    source_path=facts.relative_path,
                    symbol=facts.qualified(route.function_name),
                    line_start=route.decorator_lineno,
                    line_end=route.decorator_lineno,
                )
                for node in model_reference_nodes(route.response_model):
                    link_schema(
                        facts=facts,
                        node=node,
                        role=RESPONSE_ROLE,
                        endpoint_identifier=identifier,
                        provenance=decorator_provenance,
                        type_expression=route.response_model_expression,
                    )
                for parameter in _body_parameters(route, path_parameters):
                    parameter_provenance = Provenance(
                        repository=repository,
                        commit=commit,
                        source_path=facts.relative_path,
                        symbol=f"{facts.qualified(route.function_name)}.{parameter.name}",
                        line_start=parameter.lineno,
                        line_end=parameter.lineno,
                    )
                    for node in model_reference_nodes(parameter.annotation):
                        link_schema(
                            facts=facts,
                            node=node,
                            role=REQUEST_ROLE,
                            endpoint_identifier=identifier,
                            provenance=parameter_provenance,
                            type_expression=parameter.annotation_expression,
                            parameter=parameter.name,
                        )

    # --- APIs, ownership, and containment -------------------------------------------------
    surfaces_by_service: dict[str, list[tuple[NodeKey, SurfaceDefinition]]] = {}
    for node in sorted(
        graph.surfaces, key=lambda item: (item.service, item.module, item.variable)
    ):
        surfaces_by_service.setdefault(node.service, []).append((node, graph.surfaces[node]))

    apis: list[ApiCandidate] = []
    for service in sorted(surfaces_by_service):
        items = surfaces_by_service[service]
        app_items = [pair for pair in items if pair[1].is_app]
        anchor_node, anchor_surface = (app_items or items)[0]
        anchor_facts = index.facts(service, anchor_node.module)
        service_endpoints = sorted(
            item.id for item in endpoints.values() if item.service == service
        )
        partial_paths = sum(
            1
            for item in endpoints.values()
            if item.service == service and item.path_resolution == "partial"
        )
        identifier = api_id(repository_slug, service)
        attributes: dict[str, Any] = {
            "framework": EXTRACTOR_KIND,
            "application_count": len(app_items),
            "router_count": len(items) - len(app_items),
            "endpoint_count": len(service_endpoints),
            "endpoints_with_partial_paths": partial_paths,
        }
        anchor_symbol = (
            f"{anchor_node.module}.{anchor_node.variable}"
            if anchor_node.module
            else anchor_node.variable
        )
        if anchor_surface.is_app:
            attributes["application_symbol"] = anchor_symbol
            if anchor_surface.title:
                attributes["application_title"] = anchor_surface.title
            if anchor_surface.root_path_expression:
                attributes["root_path_expression"] = anchor_surface.root_path_expression
                warnings.append(
                    f"{service}: FastAPI(root_path=...) is declared but is a deployment "
                    f"concern; it is recorded and never composed into an endpoint path"
                )
        else:
            attributes["anchor_router_symbol"] = anchor_symbol
            warnings.append(
                f"{service}: routers were found but no FastAPI(...) application; the API "
                f"candidate is anchored on {anchor_symbol}"
            )

        provenance = Provenance(
            repository=repository,
            commit=commit,
            source_path=anchor_facts.relative_path if anchor_facts else anchor_node.module,
            symbol=anchor_symbol,
            line_start=anchor_surface.lineno,
            line_end=anchor_surface.end_lineno,
        )
        title = (
            anchor_surface.title
            if anchor_surface.is_app and anchor_surface.title
            else f"{service} HTTP API"
        )
        apis.append(
            ApiCandidate(
                id=identifier,
                kind=API_KIND,
                title=title,
                service=service,
                service_entity_id=service_id(repository_slug, service),
                provenance=provenance,
                attributes=attributes,
            )
        )
        relationships.append(
            RelationshipCandidate(
                source=service_id(repository_slug, service),
                type=EXPOSES,
                target=identifier,
                provenance=provenance,
                detail={"framework": EXTRACTOR_KIND},
            )
        )
        for endpoint_identifier in service_endpoints:
            endpoint = endpoints[endpoint_identifier]
            relationships.append(
                RelationshipCandidate(
                    source=identifier,
                    type=CONTAINS,
                    target=endpoint_identifier,
                    provenance=endpoint.provenance,
                    detail={"method": endpoint.method, "path": endpoint.effective_path},
                )
            )

    api_ids = {item.service: item.id for item in apis}
    services_scanned = tuple(
        ServiceScan(
            slug=slug,
            entity_id=service_id(repository_slug, slug),
            python_files=files_per_service[slug],
            surfaces=len(surfaces_by_service.get(slug, ())),
            endpoints=sum(1 for item in endpoints.values() if item.service == slug),
            api=api_ids.get(slug),
        )
        for slug in sorted(files_per_service)
    )
    for scan in services_scanned:
        if scan.surfaces == 0:
            warnings.append(
                f"{scan.slug}: {scan.python_files} Python file(s) scanned and no FastAPI or "
                f"APIRouter construct found; no API candidate was created for "
                f"{scan.entity_id}"
            )

    discovered_models: list[str] = []
    for facts in modules:
        for class_name in sorted(facts.classes):
            if index.is_pydantic_model(facts.service, facts.module, class_name):
                discovered_models.append(f"{facts.service}:{facts.qualified(class_name)}")

    return FastApiExtraction(
        repository=repository,
        commit=commit,
        owner=record.owner,
        source_files=tuple(scanned),
        skipped_files=tuple(sorted(skipped)),
        services_scanned=services_scanned,
        apis=tuple(sorted(apis, key=lambda item: item.id)),
        endpoints=tuple(sorted(endpoints.values(), key=lambda item: item.id)),
        schemas=tuple(sorted(schemas.values(), key=lambda item: item.id)),
        relationships=tuple(
            sorted(
                relationships,
                key=lambda item: (item.source, item.type, item.target, item.role or ""),
            )
        ),
        unresolved_routes=tuple(
            sorted(
                unresolved_routes,
                key=lambda item: (
                    item.reason_code,
                    item.provenance.source_path,
                    item.provenance.line_start or 0,
                    item.detail,
                ),
            )
        ),
        unresolved_schemas=tuple(
            sorted(
                unresolved_schemas,
                key=lambda item: (item.role, item.endpoint or "", item.expression, item.detail),
            )
        ),
        discovered_models=tuple(sorted(discovered_models)),
        warnings=tuple(warnings),
        withheld_values=frozenset(withheld),
    )



def _relation_entries(relations: tuple[RelationshipCandidate, ...]) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    for relation in relations:
        entry: dict[str, Any] = {"type": relation.type, "target": relation.target}
        if relation.role:
            entry["role"] = relation.role
        entry.update(relation.detail)
        entry.update(relation.provenance.as_dict())
        entries.append(entry)
    return entries


def _inbound_entries(relations: tuple[RelationshipCandidate, ...]) -> list[dict[str, Any]]:
    entries: list[dict[str, Any]] = []
    for relation in relations:
        entry: dict[str, Any] = {"type": relation.type, "source": relation.source}
        if relation.role:
            entry["role"] = relation.role
        entry.update(relation.detail)
        entry.update(relation.provenance.as_dict())
        entries.append(entry)
    return entries


def _render_page(frontmatter: dict[str, Any], body: list[str]) -> str:
    rendered = yaml.safe_dump(
        frontmatter,
        sort_keys=False,
        default_flow_style=False,
        allow_unicode=True,
        width=100,
    ).rstrip("\n")
    return "\n".join(["---", rendered, "---", "", *body, ""])


def _base_frontmatter(
    *,
    identifier: str,
    kind: str,
    title: str,
    extraction: FastApiExtraction,
    service_entity_id: str,
) -> dict[str, Any]:
    """Frontmatter shared by every candidate page. Never approved, never canonical."""
    frontmatter: dict[str, Any] = {
        "id": identifier,
        "kind": kind,
        # The canonical loader requires kind and OKF type to agree.
        "type": kind,
        "title": title,
        "status": CANDIDATE_STATUS,
        "review_status": CANDIDATE_REVIEW_STATUS,
        "candidate_of": f"{EXTRACTOR_KIND}-extraction",
        "repository": extraction.repository,
        "commit": extraction.commit,
        "evidence_type": EVIDENCE_TYPE,
        "extractor": EXTRACTOR_KIND,
        "service": service_entity_id,
    }
    if extraction.owner:
        frontmatter["owner"] = extraction.owner
    return frontmatter


def render_api_markdown(api: ApiCandidate, extraction: FastApiExtraction) -> str:
    frontmatter = _base_frontmatter(
        identifier=api.id,
        kind=api.kind,
        title=api.title,
        extraction=extraction,
        service_entity_id=api.service_entity_id,
    )
    frontmatter["source_refs"] = [api.provenance.as_dict()]
    inbound = extraction.inbound_relations_for(api.id)
    if inbound:
        frontmatter["inbound_relations"] = _inbound_entries(inbound)
    relations = extraction.relations_for(api.id)
    if relations:
        frontmatter["relations"] = _relation_entries(relations)
    if api.attributes:
        frontmatter["attributes"] = api.attributes

    body = [
        f"# {api.title}",
        "",
        f"Candidate FastAPI surface extracted from Python source in `{extraction.repository}` "
        f"at commit `{extraction.commit}`.",
        "",
        f"- Owning service: `{api.service_entity_id}`",
        f"- Declared in: `{api.provenance.source_path}`",
        f"- Symbol: `{api.provenance.symbol}`",
        f"- Evidence class: `{EVIDENCE_TYPE}`",
        "",
    ]
    if relations:
        body.extend(["## Endpoints", ""])
        body.extend(f"- `{relation.type}` -> `{relation.target}`" for relation in relations)
        body.append("")
    body.extend(
        [
            "## Review notes",
            "",
            "This page is a candidate awaiting review. It is not canonical knowledge. Paths "
            "come from statically resolvable decorators and router prefixes only.",
            "",
        ]
    )
    return _render_page(frontmatter, body)


def render_endpoint_markdown(
    endpoint: EndpointCandidate, extraction: FastApiExtraction
) -> str:
    frontmatter = _base_frontmatter(
        identifier=endpoint.id,
        kind=endpoint.kind,
        title=endpoint.title,
        extraction=extraction,
        service_entity_id=service_id(normalize_token(extraction.repository), endpoint.service),
    )
    frontmatter["api"] = endpoint.api
    frontmatter["method"] = endpoint.method
    frontmatter["effective_path"] = endpoint.effective_path
    frontmatter["path_resolution"] = endpoint.path_resolution
    frontmatter["source_refs"] = [endpoint.provenance.as_dict()]
    inbound = extraction.inbound_relations_for(endpoint.id)
    if inbound:
        frontmatter["inbound_relations"] = _inbound_entries(inbound)
    relations = extraction.relations_for(endpoint.id)
    if relations:
        frontmatter["relations"] = _relation_entries(relations)
    if endpoint.attributes:
        frontmatter["attributes"] = endpoint.attributes

    body = [
        f"# {endpoint.title}",
        "",
        f"Candidate HTTP endpoint extracted from a FastAPI route decorator in "
        f"`{extraction.repository}` at commit `{extraction.commit}`.",
        "",
        f"- Method: `{endpoint.method}`",
        f"- Effective path: `{endpoint.effective_path}`",
        f"- Path resolution: `{endpoint.path_resolution}`",
        f"- Handler: `{endpoint.provenance.symbol}`",
        f"- Declared in: `{endpoint.provenance.source_path}` "
        f"(lines {endpoint.provenance.line_start}-{endpoint.provenance.line_end})",
        f"- Evidence class: `{EVIDENCE_TYPE}`",
        "",
    ]
    if endpoint.path_resolution == "partial":
        expressions = endpoint.attributes.get("unresolved_prefix_expressions", [])
        body.extend(
            [
                "## Unresolved mount prefix",
                "",
                "The effective path above omits a mount prefix that is not a string literal "
                "in source, so the served path depends on configuration:",
                "",
            ]
        )
        body.extend(f"- `{expression}`" for expression in expressions)
        body.append("")
    if relations:
        body.extend(["## Schemas", ""])
        body.extend(
            f"- `{relation.role}` `{relation.type}` -> `{relation.target}`"
            for relation in relations
        )
        body.append("")
    body.extend(
        [
            "## Review notes",
            "",
            "This page is a candidate awaiting review. Method and path come from the "
            "decorator shown in `attributes.decorator`; nothing was inferred from names.",
            "",
        ]
    )
    return _render_page(frontmatter, body)


def render_schema_markdown(schema: SchemaCandidate, extraction: FastApiExtraction) -> str:
    frontmatter = _base_frontmatter(
        identifier=schema.id,
        kind=schema.kind,
        title=schema.title,
        extraction=extraction,
        service_entity_id=service_id(normalize_token(extraction.repository), schema.service),
    )
    frontmatter["qualified_name"] = schema.qualified_name
    frontmatter["pydantic_confirmed"] = schema.pydantic_confirmed
    frontmatter["base_resolution"] = schema.base_resolution
    if schema.bases:
        frontmatter["bases"] = list(schema.bases)
    frontmatter["source_refs"] = [schema.provenance.as_dict()]
    inbound = extraction.inbound_relations_for(schema.id)
    if inbound:
        frontmatter["inbound_relations"] = _inbound_entries(inbound)
    if schema.fields:
        frontmatter["fields"] = schema.field_summaries()

    roles = sorted({relation.role or "" for relation in inbound if relation.role})
    body = [
        f"# {schema.title}",
        "",
        f"Candidate schema extracted from a class definition in `{extraction.repository}` at "
        f"commit `{extraction.commit}`.",
        "",
        f"- Qualified name: `{schema.qualified_name}`",
        f"- Declared in: `{schema.provenance.source_path}` "
        f"(lines {schema.provenance.line_start}-{schema.provenance.line_end})",
        f"- Pydantic BaseModel confirmed in source: `{schema.pydantic_confirmed}`",
        f"- Base resolution: `{schema.base_resolution}`",
        f"- Used as: `{', '.join(roles) if roles else 'unreferenced'}`",
        f"- Evidence class: `{EVIDENCE_TYPE}`",
        "",
        "## Review notes",
        "",
        "This page is a candidate awaiting review. Field annotations are recorded as source "
        "text and never evaluated; credential-shaped defaults are redacted at extraction "
        "time.",
        "",
    ]
    return _render_page(frontmatter, body)


def render_all(extraction: FastApiExtraction) -> dict[str, str]:
    """Render every candidate page keyed by output-relative POSIX path."""
    rendered: dict[str, str] = {}
    for api in extraction.apis:
        rendered[f"apis/{api.id}.md"] = render_api_markdown(api, extraction)
    for endpoint in extraction.endpoints:
        rendered[f"endpoints/{endpoint.id}.md"] = render_endpoint_markdown(endpoint, extraction)
    for schema in extraction.schemas:
        rendered[f"schemas/{schema.id}.md"] = render_schema_markdown(schema, extraction)
    return rendered


def build_report(extraction: FastApiExtraction, secret_values_emitted: int) -> dict[str, Any]:
    """Assemble extraction-report.json. Contains no timestamp, so runs stay comparable."""
    method_counts: dict[str, int] = {}
    for endpoint in extraction.endpoints:
        method_counts[endpoint.method] = method_counts.get(endpoint.method, 0) + 1
    relationship_counts: dict[str, int] = {}
    for relation in extraction.relationships:
        relationship_counts[relation.type] = relationship_counts.get(relation.type, 0) + 1

    return {
        "version": 1,
        "extractor": EXTRACTOR_KIND,
        "repository": extraction.repository,
        "commit": extraction.commit,
        "commit_verified": True,
        "evidence_type": EVIDENCE_TYPE,
        "analysis": "python-ast",
        "modules_imported": 0,
        "modules_executed": 0,
        "source_files": list(extraction.source_files),
        "skipped_files": list(extraction.skipped_files),
        "services_scanned": [scan.summary() for scan in extraction.services_scanned],
        "counts": {
            "source_files": len(extraction.source_files),
            "skipped_files": len(extraction.skipped_files),
            "services_scanned": len(extraction.services_scanned),
            "apis": len(extraction.apis),
            "endpoints": len(extraction.endpoints),
            "schemas": len(extraction.schemas),
            "relationships": len(extraction.relationships),
            "unresolved_routes": len(extraction.unresolved_routes),
            "unresolved_schemas": len(extraction.unresolved_schemas),
            "warnings": len(extraction.warnings),
            "endpoints_by_method": dict(sorted(method_counts.items())),
            "relationships_by_type": dict(sorted(relationship_counts.items())),
        },
        "apis": [api.summary() for api in extraction.apis],
        "endpoints": [endpoint.summary() for endpoint in extraction.endpoints],
        "schemas": [schema.summary() for schema in extraction.schemas],
        "relationships": [relation.summary() for relation in extraction.relationships],
        "unresolved_routes": [item.summary() for item in extraction.unresolved_routes],
        "unresolved_schemas": [item.summary() for item in extraction.unresolved_schemas],
        "discovered_pydantic_models": list(extraction.discovered_models),
        "warnings": list(extraction.warnings),
        "secret_values_emitted": secret_values_emitted,
        "graph_mutations": 0,
        "wiki_writes": 0,
        "neo4j_mutations": 0,
        "graphiti_mutations": 0,
        "graphiti": "disabled",
    }


def count_secret_leaks(extraction: FastApiExtraction, rendered: dict[str, str]) -> int:
    """Verify redaction by scanning rendered output for values that were withheld.

    ``secret_values_emitted`` in the report is this measured count, not a constant.
    """
    scannable = {
        value
        for value in extraction.withheld_values
        if len(value.strip()) >= _MIN_SCANNABLE_SECRET_LENGTH and not value.strip().isdigit()
    }
    leaks = 0
    for content in rendered.values():
        for secret in sorted(scannable):
            leaks += content.count(secret)
    return leaks


def render_report_json(report: dict[str, Any]) -> str:
    return json.dumps(report, indent=2, ensure_ascii=False) + "\n"


def render_bundle(extraction: FastApiExtraction) -> tuple[dict[str, str], dict[str, Any]]:
    """Render candidates plus the report, with the leak count measured over all output."""
    rendered = render_all(extraction)
    provisional = build_report(extraction, 0)
    scanned = {**rendered, "extraction-report.json": render_report_json(provisional)}
    leaks = count_secret_leaks(extraction, scanned)
    return rendered, build_report(extraction, leaks)



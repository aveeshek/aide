def normalize_token(value: str) -> str:
    """Lowercase ``value`` and reduce every run of non-alphanumerics to a single hyphen."""
    lowered = str(value).strip().lower()
    return re.sub(r"[^a-z0-9]+", "-", lowered).strip("-")


def normalize_dotted(value: str) -> str:
    """Normalize a dotted symbol path, preserving ``.`` as the only separator."""
    parts = [normalize_token(part) for part in str(value).split(".")]
    return ".".join(part for part in parts if part)


def is_secret_name(name: str) -> bool:
    """True when ``name`` looks like it holds a credential."""
    upper = str(name).upper()
    return any(marker in upper for marker in SECRET_KEY_MARKERS)


def contains_secret_marker(text: str) -> bool:
    """True when free text mentions a credential-shaped name."""
    upper = str(text).upper()
    return any(marker in upper for marker in SECRET_KEY_MARKERS)


def join_route_path(prefix: str, path: str) -> str:
    """Concatenate a resolved prefix chain and a decorator path the way FastAPI does.

    FastAPI performs plain string concatenation: a router prefix must not end with ``/``
    and a route path must start with ``/``. The concatenation is preserved verbatim, so a
    declared trailing slash survives into the effective path. Only a missing leading slash
    is added, which normalizes presentation without changing any declared segment.
    """
    combined = f"{prefix}{path}"
    if not combined:
        return "/"
    if not combined.startswith("/"):
        combined = f"/{combined}"
    return combined


def normalize_path_segment(segment: str) -> str:
    """Normalize one path segment; a path parameter becomes a stable dash token.

    ``{user_id}`` and ``{user_id:path}`` both become ``user-id``, so an id stays readable
    and stable while never embedding a converter or brace.
    """
    match = re.fullmatch(r"\{([^{}]*)\}", segment.strip())
    if match:
        name = match.group(1).split(":", 1)[0]
        return normalize_token(name)
    return normalize_token(segment)


def endpoint_path_tokens(effective_path: str) -> tuple[str, ...]:
    """Split an effective path into normalized, dot-joinable id tokens."""
    trimmed = str(effective_path).strip().strip("/")
    if not trimmed:
        return (_EMPTY_PATH_TOKEN,)
    tokens = [normalize_path_segment(segment) for segment in trimmed.split("/")]
    populated = tuple(token for token in tokens if token)
    return populated or (_EMPTY_PATH_TOKEN,)


def api_id(repository_slug: str, service_slug: str) -> str:
    return f"api.{repository_slug}.{service_slug}"


def service_id(repository_slug: str, service_slug: str) -> str:
    return f"service.{repository_slug}.{service_slug}"


def endpoint_id(
    repository_slug: str, service_slug: str, method: str, effective_path: str
) -> str:
    """Build a byte-stable endpoint id from service, HTTP method, and effective path."""
    tokens = ".".join(endpoint_path_tokens(effective_path))
    return f"endpoint.{repository_slug}.{service_slug}.{method.lower()}.{tokens}"


def schema_id(repository_slug: str, service_slug: str, qualified_name: str) -> str:
    """Build a byte-stable schema id from the Python qualified name of the class."""
    return f"schema.{repository_slug}.{service_slug}.{normalize_dotted(qualified_name)}"


def module_dotted_name(relative_path: str, service_root: str) -> str:
    """Return the dotted module name of a file relative to its service source root."""
    remainder = relative_path[len(service_root) :].lstrip("/")
    parts = remainder[: -len(PYTHON_SUFFIX)].split("/")
    if parts and parts[-1] == "__init__":
        parts = parts[:-1]
    while parts and parts[0] in SOURCE_ROOT_DIRECTORY_NAMES:
        parts = parts[1:]
    return ".".join(part for part in parts if part)


def service_location(relative_path: str) -> tuple[str, str] | None:
    """Map a repository-relative POSIX path to ``(service slug, service root)``.

    Ownership follows repository layout only:

    * ``backend/gateway/**``               -> ``gateway``
    * ``backend/microservices/<name>/**``  -> ``<name>``

    Returning ``None`` means the file is outside the known application layout and is not
    attributed to any service.
    """
    parts = relative_path.split("/")
    if len(parts) < 3 or parts[0] != BACKEND_SEGMENT:
        return None
    if parts[1] == GATEWAY_SEGMENT:
        return GATEWAY_SEGMENT, f"{BACKEND_SEGMENT}/{GATEWAY_SEGMENT}"
    if parts[1] == MICROSERVICES_SEGMENT and len(parts) >= 4 and parts[2]:
        slug = normalize_token(parts[2])
        if not slug:
            return None
        return slug, f"{BACKEND_SEGMENT}/{MICROSERVICES_SEGMENT}/{parts[2]}"
    return None


def _expression_text(source: str, node: ast.AST | None) -> str | None:
    """Return the collapsed source text of ``node``, never an evaluated value."""
    if node is None:
        return None
    try:
        segment = ast.get_source_segment(source, node)
    except (ValueError, IndexError, TypeError):
        return None
    if segment is None:
        return None
    collapsed = " ".join(segment.split())
    if not collapsed:
        return None
    return collapsed[:_MAX_EXPRESSION_LENGTH]


def _dotted_expression(node: ast.expr) -> str | None:
    """Flatten ``a.b.c`` into ``"a.b.c"``; return None for any other expression shape."""
    parts: list[str] = []
    current: ast.expr = node
    while isinstance(current, ast.Attribute):
        parts.append(current.attr)
        current = current.value
    if not isinstance(current, ast.Name):
        return None
    parts.append(current.id)
    return ".".join(reversed(parts))


def _constant_string(node: ast.expr | None) -> str | None:
    if isinstance(node, ast.Constant) and isinstance(node.value, str):
        return node.value
    return None


def _constant_strings(node: ast.expr | None) -> tuple[str, ...]:
    """Read a statically declared list/tuple of string constants."""
    if not isinstance(node, ast.List | ast.Tuple):
        return ()
    values = [_constant_string(element) for element in node.elts]
    return tuple(value for value in values if value is not None)


def _keyword_node(call: ast.Call, name: str) -> ast.expr | None:
    for keyword in call.keywords:
        if keyword.arg == name:
            return keyword.value
    return None



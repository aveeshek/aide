"""Deterministic FastAPI extractor (Graph Engineering Pass 2).

Scope and non-goals
-------------------
This extractor reads Python source with :mod:`ast` and emits *candidates* only. It never
imports or executes the inspected application, never starts a service, never writes
canonical knowledge, never touches Neo4j or Graphiti, and never calls an LLM.

It records only what the Python source states explicitly:

* FastAPI application and router surfaces (``FastAPI(...)`` / ``APIRouter(...)``)
* HTTP endpoints declared through route decorators
* request and response schemas that resolve to a class definition in scanned source
* ``Service -EXPOSES-> API``, ``API -CONTAINS-> Endpoint``, ``Endpoint -USES_SCHEMA-> Schema``

Message-broker producers and consumers, database models, runtime consumers, and business
flow relationships are out of scope for this pass and are never inferred.

Determinism
-----------
Every identifier is derived from source text: repository slug, service slug, HTTP method,
and the statically resolved effective path. No hash, counter, timestamp, or absolute
workstation path enters the output, so re-running against an unchanged commit produces
byte-identical candidates.

Honesty over completeness
-------------------------
A path, prefix, response model, or body annotation that is not statically resolvable is
recorded as an unresolved item with the offending source expression. It is never guessed.
An endpoint whose decorator path is dynamic is not emitted at all, because its path cannot
be known from source. An endpoint whose *prefix* chain is partly dynamic is emitted with
``path_resolution: partial`` and the unresolved expressions attached, because the route
itself is proven by the decorator even though its mount point is configuration-driven.
"""


@dataclass(frozen=True, slots=True)
class NodeKey:
    """Identity of a mountable surface: one variable in one module of one service."""

    service: str
    module: str
    variable: str

    def describe(self) -> str:
        return f"{self.module}:{self.variable}" if self.module else self.variable


@dataclass(frozen=True, slots=True)
class MountEdge:
    """One ``include_router`` mount: parent surface, child surface, contributed prefix."""

    parent: NodeKey
    child: NodeKey
    prefix: str
    prefix_resolved: bool
    prefix_expression: str | None
    relative_path: str
    lineno: int


@dataclass(frozen=True, slots=True)
class PrefixChain:
    """A statically resolved mount path for one surface."""

    prefix: str
    resolved: bool
    unresolved_expressions: tuple[str, ...]
    mount_path: tuple[str, ...]


@dataclass(frozen=True, slots=True)
class RouterGraph:
    surfaces: dict[NodeKey, SurfaceDefinition]
    incoming: dict[NodeKey, tuple[MountEdge, ...]]

    def own_prefix(self, node: NodeKey) -> tuple[str, bool, tuple[str, ...]]:
        surface = self.surfaces.get(node)
        if surface is None:
            return "", True, ()
        if surface.prefix_resolved:
            return surface.prefix, True, ()
        expression = surface.prefix_expression or "<dynamic>"
        return "", False, (expression,)

    def chains(
        self, node: NodeKey, *, _seen: frozenset[NodeKey] = frozenset()
    ) -> tuple[PrefixChain, ...]:
        """Enumerate every distinct mount path that reaches ``node``.

        A surface mounted at two places really is served at two paths, so each distinct
        chain becomes its own endpoint rather than one arbitrary winner.
        """
        own_prefix, own_resolved, own_unresolved = self.own_prefix(node)
        parents = self.incoming.get(node, ())
        base = PrefixChain(
            prefix=own_prefix,
            resolved=own_resolved,
            unresolved_expressions=own_unresolved,
            mount_path=(node.describe(),),
        )
        if not parents:
            return (base,)

        collected: list[PrefixChain] = []
        for edge in parents:
            if edge.parent in _seen or edge.parent == node:
                # Mount cycle: stop here rather than recursing forever.
                continue
            for parent_chain in self.chains(edge.parent, _seen=_seen | {node}):
                edge_unresolved = (
                    () if edge.prefix_resolved else (edge.prefix_expression or "<dynamic>",)
                )
                collected.append(
                    PrefixChain(
                        prefix=f"{parent_chain.prefix}{edge.prefix}{own_prefix}",
                        resolved=(
                            parent_chain.resolved and edge.prefix_resolved and own_resolved
                        ),
                        unresolved_expressions=(
                            parent_chain.unresolved_expressions
                            + edge_unresolved
                            + own_unresolved
                        ),
                        mount_path=parent_chain.mount_path + (node.describe(),),
                    )
                )
        if not collected:
            return (base,)

        # Distinct effective prefixes only; identical chains reached twice are one path.
        unique: dict[str, PrefixChain] = {}
        for chain in collected:
            unique.setdefault(chain.prefix, chain)
        return tuple(unique[key] for key in sorted(unique))



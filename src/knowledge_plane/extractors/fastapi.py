# Resolution kinds. ``local`` kinds name a definition found in scanned source; ``external``
# means the defining module is outside the scanned tree; ``unknown`` means the name could
# not be traced at all.
RESOLUTION_CLASS = "class"
RESOLUTION_ROUTER = "router"
RESOLUTION_APP = "app"
RESOLUTION_FACTORY = "factory"
RESOLUTION_FUNCTION = "function"
RESOLUTION_MODULE = "module"
RESOLUTION_EXTERNAL = "external"
RESOLUTION_UNKNOWN = "unknown"


@dataclass(frozen=True, slots=True)
class Resolution:
    """The outcome of tracing a name to its definition."""

    kind: str
    module: str | None = None
    name: str | None = None
    reason: str | None = None

    @property
    def is_local(self) -> bool:
        return self.kind in (
            RESOLUTION_CLASS,
            RESOLUTION_ROUTER,
            RESOLUTION_APP,
            RESOLUTION_FACTORY,
            RESOLUTION_FUNCTION,
        )


@dataclass(frozen=True, slots=True)
class SourceIndex:
    """All analyzed modules, addressable by dotted name and by dotted suffix.

    Suffix lookup exists because a repository's ``sys.path`` root is not knowable from the
    filesystem alone. A suffix is only usable when it identifies exactly one module, so an
    ambiguous import resolves to nothing rather than to a guess.
    """

    modules: dict[tuple[str, str], ModuleFacts]
    suffixes: dict[tuple[str, str], frozenset[str]]

    def facts(self, service: str, module: str) -> ModuleFacts | None:
        return self.modules.get((service, module))

    def resolve_module(
        self, service: str, current_module: str, imported: ImportedSymbol
    ) -> str | None:
        """Resolve an import target to a scanned module name, or None when external."""
        if imported.level:
            facts = self.facts(service, current_module)
            parts = current_module.split(".") if current_module else []
            base = parts if (facts is not None and facts.is_package) else parts[:-1]
            drop = imported.level - 1
            if drop:
                base = base[:-drop] if drop <= len(base) else []
            tail = imported.module.split(".") if imported.module else []
            target = ".".join(part for part in [*base, *tail] if part)
        else:
            target = imported.module
        if not target:
            return None
        if (service, target) in self.modules:
            return target
        candidates = self.suffixes.get((service, target))
        if candidates and len(candidates) == 1:
            return next(iter(candidates))
        return None

    def resolve_name(
        self,
        service: str,
        module: str,
        name: str,
        *,
        _seen: frozenset[tuple[str, str, str]] = frozenset(),
    ) -> Resolution:
        """Trace ``name`` from ``module`` to its definition, following import aliases.

        Re-export chains matter: FTGO mounts routers imported from a package ``__init__``
        that itself re-exports ``router`` from a submodule, so a single hop is not enough.
        """
        if len(_seen) > _MAX_RESOLUTION_DEPTH:
            return Resolution(
                RESOLUTION_UNKNOWN, module, name, reason="import chain exceeded depth limit"
            )
        facts = self.facts(service, module)
        if facts is None:
            return Resolution(
                RESOLUTION_EXTERNAL, module, name, reason="module is outside scanned source"
            )
        if name in facts.classes:
            return Resolution(RESOLUTION_CLASS, module, name)
        surface = facts.surfaces.get(name)
        if surface is not None:
            kind = RESOLUTION_APP if surface.is_app else RESOLUTION_ROUTER
            return Resolution(kind, module, name)
        if name in facts.factories:
            return Resolution(RESOLUTION_FACTORY, module, name)
        if name in facts.functions:
            return Resolution(RESOLUTION_FUNCTION, module, name)

        imported = facts.imports.get(name)
        if imported is None:
            return Resolution(
                RESOLUTION_UNKNOWN,
                module,
                name,
                reason="name is not defined or imported in this module",
            )
        target_module = self.resolve_module(service, module, imported)
        if target_module is None:
            return Resolution(
                RESOLUTION_EXTERNAL,
                imported.module or module,
                imported.name or name,
                reason="imported from a module outside scanned source",
            )
        if imported.name is None:
            return Resolution(RESOLUTION_MODULE, target_module, None)
        key = (service, target_module, imported.name)
        if key in _seen:
            return Resolution(
                RESOLUTION_UNKNOWN, target_module, imported.name, reason="import cycle"
            )
        return self.resolve_name(
            service, target_module, imported.name, _seen=_seen | {key}
        )

    def resolve_expression(self, service: str, module: str, node: ast.expr) -> Resolution:
        """Resolve a ``Name`` or dotted ``Attribute`` expression to a definition."""
        if isinstance(node, ast.Name):
            return self.resolve_name(service, module, node.id)
        dotted = _dotted_expression(node)
        if dotted is None:
            return Resolution(
                RESOLUTION_UNKNOWN, module, None, reason="expression is not a dotted name"
            )
        parts = dotted.split(".")
        head = self.resolve_name(service, module, parts[0])
        if head.kind == RESOLUTION_MODULE and head.module is not None and len(parts) >= 2:
            return self.resolve_name(service, head.module, parts[-1])
        if head.kind == RESOLUTION_EXTERNAL:
            return Resolution(
                RESOLUTION_EXTERNAL,
                head.module,
                parts[-1],
                reason="attribute of a module outside scanned source",
            )
        return Resolution(
            RESOLUTION_UNKNOWN,
            module,
            dotted,
            reason="attribute access could not be traced to a definition",
        )

    def is_pydantic_model(
        self,
        service: str,
        module: str,
        class_name: str,
        *,
        _seen: frozenset[tuple[str, str]] = frozenset(),
    ) -> bool:
        """True when a class inherits ``pydantic.BaseModel`` through scanned source only.

        Aliased and re-exported ``BaseModel`` names resolve; a base imported from a package
        that is not part of the scanned tree cannot be proven and returns False.
        """
        if (module, class_name) in _seen or len(_seen) > _MAX_RESOLUTION_DEPTH:
            return False
        facts = self.facts(service, module)
        if facts is None:
            return False
        declaration = facts.classes.get(class_name)
        if declaration is None:
            return False
        for base in declaration.base_nodes:
            if _resolve_framework_symbol(
                facts.imports, base, (_PYDANTIC_ROOT_MODULE,)
            ) == _PYDANTIC_BASE_MODEL:
                return True
            resolved = self.resolve_expression(service, module, base)
            if (
                resolved.kind == RESOLUTION_CLASS
                and resolved.module is not None
                and resolved.name is not None
                and self.is_pydantic_model(
                    service,
                    resolved.module,
                    resolved.name,
                    _seen=_seen | {(module, class_name)},
                )
            ):
                return True
        return False


def build_source_index(facts: list[ModuleFacts]) -> SourceIndex:
    """Index analyzed modules by exact dotted name and by every dotted suffix."""
    modules: dict[tuple[str, str], ModuleFacts] = {}
    suffix_sets: dict[tuple[str, str], set[str]] = {}
    for item in sorted(facts, key=lambda entry: (entry.service, entry.module)):
        modules.setdefault((item.service, item.module), item)
        if not item.module:
            continue
        parts = item.module.split(".")
        for start in range(len(parts)):
            key = (item.service, ".".join(parts[start:]))
            suffix_sets.setdefault(key, set()).add(item.module)
    suffixes = {key: frozenset(value) for key, value in suffix_sets.items()}
    return SourceIndex(modules=modules, suffixes=suffixes)


def model_reference_nodes(node: ast.expr | None) -> list[ast.expr]:
    """Extract named model references from a type expression, unwrapping containers.

    ``list[Model]``, ``List[Model]``, ``Optional[Model]``, ``Model | None``, and
    ``Union[A, B]`` all yield their named members. Literals and string forward references
    yield nothing, because a name that is not present as an expression cannot be traced.
    """
    if node is None:
        return []
    if isinstance(node, ast.Name | ast.Attribute):
        return [node]
    if isinstance(node, ast.Subscript):
        leaves: list[ast.expr] = []
        container = _dotted_expression(node.value)
        container_name = container.split(".")[-1] if container else None
        if container_name not in TYPING_CONTAINERS:
            leaves.extend(model_reference_nodes(node.value))
        elements = node.slice.elts if isinstance(node.slice, ast.Tuple) else [node.slice]
        for element in elements:
            leaves.extend(model_reference_nodes(element))
        return leaves
    if isinstance(node, ast.BinOp) and isinstance(node.op, ast.BitOr):
        return model_reference_nodes(node.left) + model_reference_nodes(node.right)
    return []


def _is_ignorable_annotation(node: ast.expr) -> bool:
    """True for typing containers, primitives, and framework plumbing types."""
    dotted = _dotted_expression(node)
    if dotted is None:
        return True
    tail = dotted.split(".")[-1]
    return tail in TYPING_CONTAINERS or tail in PRIMITIVE_ANNOTATIONS


